"""
corollary_discharge.py - Computational Mirror Self-Recognition (MSR) via Corollary Discharge.

Von Holst & Mittelstaedt (1950) / Sperry (1950) / Crapse & Sommer (2008):
  y_afferent(t) = y_reafferent(t) [Self] + y_exafferent(t) [Other/World]

An agent equipped with an internal forward model generates an Efference Copy (Corollary Discharge):
  y_hat(t) = ForwardModel(u(t), state(t))
  Residual Exafference: epsilon(t) = y_afferent(t) - y_hat(t)

Under the Computational Mirror Self-Recognition Test:
  - Mirror condition: Sensor input is strictly correlated with self motor output u(t).
  - Other condition: Sensor input is generated by an independent, asynchronous entity.

Key Scientific Hypothesis:
  1. ABLATED (No Corollary Discharge): Agent cannot cancel self-generated reafference;
     it experiences acute perceptual surprise (NE spike) and panics, fleeing from its own
     reflection as if it were a predator.
  2. INTACT (Adaptive Corollary Discharge): Agent's forward model learns y_hat -> y_mirror,
     canceling residual exafference to ~0. The agent remains calm (recognizes self-causality),
     while still vigorously escaping true external strangers!
"""

